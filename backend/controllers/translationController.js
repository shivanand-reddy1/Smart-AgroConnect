// Get translation
const getTranslations = (req, res) => {
  const { language } = req.query;

  if (language === "kannada") {
    res.json(translations);
  } else if (language === "english") {
    const englishTranslations = {};
    Object.keys(translations).forEach((key) => {
      englishTranslations[key] = key;
    });
    res.json(englishTranslations);
  } else {
    res.json(translations);
  }
};

// Translate text using Groq API
const translateText = async (req, res) => {
  try {
    const { text, targetLanguage, sourceLanguage } = req.body;

    if (!text) {
      return res.status(400).json({ message: "Text is required" });
    }

    // Check if it's in our static dictionary first
    if (targetLanguage === "kannada" && translations[text]) {
      return res.json({
        original: text,
        translated: translations[text],
        language: "kannada",
        source: "dictionary",
      });
    }

    // Use Groq API for dynamic translation
    const Groq = require("groq-sdk");
    const groq = new Groq({
      apiKey: process.env.GROQ_API_KEY,
    });

    let prompt;
    if (targetLanguage === "kannada") {
      prompt = `Translate the following English text to Kannada (ಕನ್ನಡ). Provide ONLY the Kannada translation without any explanations or additional text:\n\n${text}`;
    } else if (targetLanguage === "english") {
      prompt = `Translate the following Kannada text to English. Provide ONLY the English translation without any explanations or additional text:\n\n${text}`;
    } else {
      return res.status(400).json({
        message: "Invalid target language. Use 'kannada' or 'english'",
      });
    }

    const chatCompletion = await groq.chat.completions.create({
      messages: [
        {
          role: "system",
          content:
            "You are a professional translator. Provide only the translation without any additional text or explanations.",
        },
        {
          role: "user",
          content: prompt,
        },
      ],
      model: "llama-3.1-8b-instant",
      temperature: 0.3,
      max_tokens: 500,
    });

    const translatedText = chatCompletion.choices[0].message.content.trim();

    res.json({
      original: text,
      translated: translatedText,
      language: targetLanguage,
      source: "ai",
    });
  } catch (error) {
    console.error("Translation error:", error);
    res.status(500).json({
      message: "Error translating text",
      error: error.message,
    });
  }
};

// Get all available translations
const getAllTranslations = (req, res) => {
  res.json({
    total: Object.keys(translations).length,
    languages: ["English", "Kannada"],
    translations,
  });
};

module.exports = { getTranslations, translateText, getAllTranslations };
